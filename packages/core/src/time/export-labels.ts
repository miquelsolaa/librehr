import type { ChainStatus } from "./hash-chain.js";

/**
 * Document languages of the Labour Inspectorate export (TIM-006). The API
 * cannot import `@librehr/i18n` (dependency direction), so the document's
 * own labels live here, next to the serializer.
 */
export type InspectionExportLocale = "ca" | "es" | "en";

export const INSPECTION_EXPORT_LOCALES: readonly InspectionExportLocale[] = [
  "ca",
  "es",
  "en",
];

export interface InspectionExportLabels {
  title: string;
  columns: {
    employee: string;
    date: string;
    sessions: string;
    breakMinutes: string;
    workedMinutes: string;
    expectedMinutes: string;
    overtimeMinutes: string;
    anomaly: string;
    corrected: string;
    chainStatus: string;
    /** Zone of the row's date and clock times (the employee's). */
    timeZone: string;
    /** Whether the day is inside an employment period; uses yes/no values. */
    employed: string;
  };
  meta: {
    document: string;
    organization: string;
    period: string;
    scope: string;
    /** The organization's zone; each row names the employee's own. */
    timeZone: string;
    generatedAt: string;
    generatedBy: string;
    exportId: string;
  };
  scope: { employee: string; organization: string };
  chainStatus: Record<ChainStatus, string>;
  yes: string;
  no: string;
  scheduleNotConfigured: string;
  /** Page footer text, e.g. "Page 2 of 5". */
  page: (page: number, pageCount: number) => string;
}

