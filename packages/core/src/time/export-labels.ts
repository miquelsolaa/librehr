const LABELS: Record<InspectionExportLocale, InspectionExportLabels> = {
  ca,
  es,
  en,
};

/**
 * Labels of the Labour Inspectorate export document in one language.
 *
 * @example
 * inspectionExportLabels("ca").columns.date; // => "Data"
 * inspectionExportLabels("es").page(1, 3); // => "Página 1 de 3"
 */
export function inspectionExportLabels(
  locale: InspectionExportLocale,
): InspectionExportLabels {
  return LABELS[locale];
}
