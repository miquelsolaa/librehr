const TABLES: Record<PdfFont, readonly number[]> = {
  regular: HELVETICA,
  bold: HELVETICA_BOLD,
};

/**
 * Width in points of WinAnsi-encoded text (a binary string, one char per
 * byte) set in a standard font at a size.
 *
 * @example
 * textWidth("Hi", "regular", 10); // => 7.22 + 2.22 = 9.44
 */
export function textWidth(bytes: string, font: PdfFont, size: number): number {
  const table = TABLES[font];
  let units = 0;
  for (let i = 0; i < bytes.length; i++) {
    units += table[bytes.charCodeAt(i) - 32] ?? 0;
  }
  return (units * size) / 1000;
}
