import fs from "node:fs";
import path from "node:path";

interface StubEntry {
  prdId: string;
  file: string;
  line: number;
  description: string;
}

const rootDir = process.cwd();
const ignoreDirs = new Set([
  "node_modules",
  ".git",
  ".next",
  "dist",
  "storybook-static",
  "coverage",
]);

function scanDir(dir: string, entries: StubEntry[] = []): StubEntry[] {
  const items = fs.readdirSync(dir, { withFileTypes: true });
  for (const item of items) {
    if (item.isDirectory()) {
      if (!ignoreDirs.has(item.name)) {
        scanDir(path.join(dir, item.name), entries);
      }
    } else if (item.isFile() && /\.(ts|tsx|js|json|sql)$/.test(item.name)) {
      const filePath = path.join(dir, item.name);
      const content = fs.readFileSync(filePath, "utf-8");
      const lines = content.split("\n");
      lines.forEach((lineText, idx) => {
        const match = lineText.match(/TODO\(([A-Z]{3}-\d{3})\):\s*(.+)/);
        if (match && match[1] && match[2]) {
          entries.push({
            prdId: match[1],
            file: path.relative(rootDir, filePath).replace(/\\/g, "/"),
            line: idx + 1,
            description: match[2].trim(),
          });
        }
      });
    }
  }
  return entries;
}

const stubs = scanDir(rootDir);
stubs.sort(
  (a, b) => a.prdId.localeCompare(b.prdId) || a.file.localeCompare(b.file),
);

let md = "# LibreHR Stubs Registry\n\n";
md +=
  "Auto-generated by `pnpm stubs:list`. Tracks all stubbed requirements and code locations.\n\n";
md += "| PRD ID | File | Line | Description |\n";
md += "|---|---|---|---|\n";

for (const stub of stubs) {
  md += `| ${stub.prdId} | \`${stub.file}\` | ${stub.line} | ${stub.description} |\n`;
}

if (stubs.length === 0) {
  md += "| - | - | - | No stubs found |\n";
}

const docsDir = path.join(rootDir, "docs");
if (!fs.existsSync(docsDir)) {
  fs.mkdirSync(docsDir, { recursive: true });
}
fs.writeFileSync(path.join(docsDir, "stubs.md"), md, "utf-8");
process.stdout.write(`Updated docs/stubs.md with ${stubs.length} stubs.\n`);
